"""Convert, solve and compare every DWSIM sample flowsheet; write docs/validation.md.

Usage (needs a checkout of https://github.com/DanWBR/dwsim for the samples):

    python validation/run_samples.py /path/to/dwsim/PlatformFiles/Common  [--jobs 4]

Each file runs in its own process with a time limit, so one crash or hang does
not stop the survey. Results are also written as JSON lines next to the report.
"""
from __future__ import annotations

import argparse
import concurrent.futures as cf
import glob
import json
import math
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

WORKER = r"""
import json, logging, math, sys, time
for n in ("idaes", "pyomo"):
    logging.getLogger(n).setLevel(logging.CRITICAL)
from dwsim2idaes import ConversionError, convert_file, validate
path = sys.argv[1]
out = {"file": path}
for cut in (False, True):
    try:
        c = convert_file(path, cut_unsupported=cut)
        break
    except ConversionError as e:
        out["strict_problem" if not cut else "problem"] = e.problems[0][:200]
        c = None
if c is not None:
    out.update(mode="cut" if cut else "strict", units=len(c.units), cut=len(c.cut_units),
               model=c.thermo["model"], ncomp=len(c.thermo["components"]))
    try:
        v = validate(c)
        duties = [d for d in v.duties if math.isfinite(d["rel"]) and abs(d["dwsim_W"]) > 1.0]
        out.update(status=v.status, optimal=v.optimal, seconds=round(v.seconds, 1),
                   init_failed=len(v.init_failed), summary=v.summary,
                   max_duty_dev=max((abs(d["rel"]) for d in duties), default=None))
    except Exception as e:
        out.update(status="error: " + str(e)[:150], optimal=False)
print("RESULT " + json.dumps(out))
"""


def run_one(path: str, timeout: float) -> dict:
    try:
        p = subprocess.run([sys.executable, "-c", WORKER, path], capture_output=True, text=True,
                           timeout=timeout)
        for line in p.stdout.splitlines():
            if line.startswith("RESULT "):
                return json.loads(line[7:])
        return {"file": path, "status": f"crashed (exit {p.returncode})", "optimal": False}
    except subprocess.TimeoutExpired:
        return {"file": path, "status": f"timeout after {timeout:.0f} s", "optimal": False}


def fmt(x, spec):
    return "" if x is None or (isinstance(x, float) and not math.isfinite(x)) else format(x, spec)


def report(rows) -> str:
    conv = [r for r in rows if r.get("mode")]
    ok = [r for r in conv if r.get("optimal")]
    strict = [r for r in conv if r["mode"] == "strict"]
    L = ["# Validation against the DWSIM sample flowsheets", "",
         "Generated by `validation/run_samples.py`. Each sample from the DWSIM repository",
         "(`PlatformFiles/Common/samples` and `tests`) was converted (strictly if possible, otherwise",
         "with `--cut-unsupported`), built, initialised from the stored DWSIM solution and solved",
         "with IPOPT. Deviations compare the IDAES solution with the results stored in the file.", "",
         f"- files read: {len(rows)}",
         f"- convertible: {len(conv)} ({len(strict)} without cutting anything)",
         f"- solved to an optimal point: {len(ok)} of {len(conv)}", "",
         "Columns: units converted / cut; worst absolute temperature deviation (K), worst relative",
         "flow deviation, worst vapour-fraction deviation over calculated streams; worst relative",
         "deviation of a duty or power. A deviation is only meaningful when the status is optimal.",
         "", "| file | mode | units / cut | model | status | max dT (K) | max dF | max dvf | max duty dev |",
         "|---|---|---|---|---|---|---|---|---|"]
    for r in sorted(conv, key=lambda r: (not r.get("optimal"), r["mode"] != "strict",
                                         os.path.basename(r["file"]).lower())):
        s = r.get("summary") or {}
        L.append(f"| {os.path.basename(r['file'])} | {r['mode']} | {r['units']} / {r['cut']} | "
                 f"{r['model']} | {r.get('status', '')} | {fmt(s.get('max_abs_dT_K'), '.3g')} | "
                 f"{fmt(s.get('max_rel_dF'), '.2%')} | {fmt(s.get('max_abs_dvf'), '.3g')} | "
                 f"{fmt(r.get('max_duty_dev'), '.2%')} |")
    reasons = {}
    for r in rows:
        if not r.get("mode"):
            k = (r.get("problem") or r.get("status") or "?").split(":")[0].split("(")[0].strip()
            reasons[k] = reasons.get(k, 0) + 1
    L += ["", "## Files that could not be converted", "", "| reason | files |", "|---|---|"]
    for k, n in sorted(reasons.items(), key=lambda kv: -kv[1]):
        L.append(f"| {k} | {n} |")
    return "\n".join(L) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("folder", help="DWSIM PlatformFiles/Common folder (or any folder of samples)")
    ap.add_argument("--jobs", type=int, default=max(1, (os.cpu_count() or 2) // 2))
    ap.add_argument("--timeout", type=float, default=600)
    ap.add_argument("--out", default=os.path.join(ROOT, "docs", "validation.md"))
    a = ap.parse_args()
    files = sorted(set(glob.glob(os.path.join(a.folder, "**", "*.dwxm[lz]"), recursive=True)))
    rows = []
    with cf.ThreadPoolExecutor(a.jobs) as ex:
        for r in ex.map(lambda f: run_one(f, a.timeout), files):
            rows.append(r)
            print(os.path.basename(r["file"]), r.get("mode", "-"), r.get("status", r.get("problem", ""))[:80],
                  flush=True)
    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    with open(a.out, "w", encoding="utf-8") as fh:
        fh.write(report(rows))
    with open(os.path.splitext(a.out)[0] + ".jsonl", "w", encoding="utf-8") as fh:
        for r in rows:
            r = dict(r, file=os.path.basename(r["file"]))
            fh.write(json.dumps(r) + "\n")
    print("wrote", a.out)


if __name__ == "__main__":
    main()
